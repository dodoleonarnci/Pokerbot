#!/usr/bin/env python3
"""Write preflop_order.py: the 169 starting hands, strongest first.

Each hand scores the average of its equity against a random hand and against
the top 25% of hands. Run it again only if you want to change that recipe.
"""
import random

from engine import RANKS
from equity import score7


def labels():
    out = []
    for i, high in enumerate(reversed(RANKS)):
        for low in reversed(RANKS[:len(RANKS) - i]):
            if high == low:
                out.append(high + low)
            else:
                out += [high + low + "s", high + low + "o"]
    return out


def combos_of(label):
    a, b = RANKS.index(label[0]), RANKS.index(label[1])
    if a == b:
        return [(a * 4 + s, a * 4 + t) for s in range(4) for t in range(s + 1, 4)]
    if label[2] == "s":
        return [tuple(sorted((a * 4 + s, b * 4 + s))) for s in range(4)]
    return [tuple(sorted((a * 4 + s, b * 4 + t))) for s in range(4) for t in range(4) if s != t]


def equity(label, opponents, samples, rng):
    wins = 0.0
    mine = combos_of(label)
    for _ in range(samples):
        hero = rng.choice(mine)
        while True:
            villain = rng.choice(opponents)
            if not set(hero) & set(villain):
                break
        used = set(hero) | set(villain)
        board = rng.sample([c for c in range(52) if c not in used], 5)
        a, b = score7(board + list(hero)), score7(board + list(villain))
        wins += 1.0 if a > b else 0.5 if a == b else 0.0
    return wins / samples


def main():
    rng = random.Random(2026)
    all_combos = [c for label in labels() for c in combos_of(label)]
    versus_random = {h: equity(h, all_combos, 30000, rng) for h in labels()}
    first = sorted(labels(), key=versus_random.get, reverse=True)

    strong, count = [], 0
    for h in first:
        if count >= 0.25 * 1326:
            break
        strong += combos_of(h)
        count = len(strong)
    versus_strong = {h: equity(h, strong, 30000, rng) for h in labels()}

    order = sorted(labels(), key=lambda h: versus_random[h] + versus_strong[h], reverse=True)
    with open("preflop_order.py", "w") as f:
        f.write('"""Generated by gen_preflop.py. Strongest first."""\nORDER = """\n')
        for i in range(0, 169, 13):
            f.write(" ".join(order[i:i + 13]) + "\n")
        f.write('""".split()\n')


if __name__ == "__main__":
    main()
